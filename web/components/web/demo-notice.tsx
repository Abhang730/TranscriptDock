"use client";

import * as React from "react";
import Link from "next/link";
import { AlertTriangle, X } from "lucide-react";
import { Alert, AlertTitle, AlertDescription } from "@/components/ui/alert";

const DISMISS_KEY = "transcriptdock.demo-notice.dismissed";

export function DemoProviderNotice() {
  const [dismissed, setDismissed] = React.useState(true);

  React.useEffect(() => {
    try {
      setDismissed(window.localStorage.getItem(DISMISS_KEY) === "1");
    } catch {
      setDismissed(false);
    }
  }, []);

  function dismiss() {
    setDismissed(true);
    try {
      window.localStorage.setItem(DISMISS_KEY, "1");
    } catch {
      // Storage can be blocked; dismissing still works for this page view.
    }
  }

  if (dismissed) return null;

  return (
    <div className="mx-auto w-full max-w-6xl px-5 pb-8 sm:px-8">
      <Alert variant="warning" className="relative items-start">
        <AlertTriangle className="mt-0.5 h-5 w-5 shrink-0" strokeWidth={3} aria-hidden />
        <div className="pr-8">
          <AlertTitle>Demo transcript provider is active</AlertTitle>
          <AlertDescription>
            Every transcript in this deployment is generated by a labelled demo
            provider. No YouTube data is fetched and no captions are transcribed
            from video. Real processing stays unavailable until an authorized
            provider is configured on the backend.{" "}
            <Link href="/faq" className="font-bold underline">
              Read what that means
            </Link>
            .
          </AlertDescription>
        </div>
        <button
          type="button"
          onClick={dismiss}
          aria-label="Dismiss demo notice"
          className="absolute right-2 top-2 flex h-7 w-7 items-center justify-center rounded border-2 border-[#0b0b0b] bg-white"
        >
          <X size={14} strokeWidth={3} aria-hidden />
        </button>
      </Alert>
    </div>
  );
}
